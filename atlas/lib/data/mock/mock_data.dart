  static Post _post({
    required String id,
    required String creatorId,
    required String origin,
    required List<String> targets,
    required String caption,
    required String intent,
    required ContentCategory category,
    required ContentType contentType,
    required ContentType postIntent,
    required List<String> subcategories,
    required List<String> topics,
    required List<String> audience,
    required String headline,
    required String summary,
    required String reason,
    MediaType mediaType = MediaType.video,
    int clip = 0,
    String language = 'en',
    int hoursAgo = 12,
    int watches = 0,
    int skips = 0,
    int completions = 0,
    int likes = 0,
    int comments = 0,
    int shares = 0,
    int saves = 0,
  }) {
    final DateTime created = _epoch.subtract(Duration(hours: hoursAgo));
    final Duration? duration = mediaType == MediaType.video
        ? Duration(seconds: sampleClips[clip].seconds)
        : null;
    return Post(
      id: id,
      creatorId: creatorId,
      mediaType: mediaType,
      mediaUrl: mediaType == MediaType.video ? sampleClips[clip].asset : null,
      mediaDuration: duration,
      caption: caption,
      creatorIntent: intent,
      originCountry: origin,
      targetCountries: targets,
      profile: AiContentProfile(
        category: category,
        contentType: contentType,
        intent: postIntent,
        subcategories: subcategories,
        topics: topics,
        audience: audience,
        language: language,
        detectedCountry: origin,
        confidence: 0.72 + (id.hashCode.abs() % 20) / 100,
        modelId: 'atlas-mock-v1',
      ),
      preview: AiPreview(
        headline: headline,
        summary: summary,
        reasonToWatch: reason,
        mediaLength: duration,
      ),
      status: PostStatus.published,
      moderation: ModerationStatus.approved,
      metrics: PostMetrics(
        watches: watches,
        skips: skips,
        completions: completions,
        likes: likes,
        comments: comments,
        shares: shares,
        saves: saves,
      ),
      createdAt: created,
      updatedAt: created,
    );
  }

