/// The content the prototype runs on.
///
/// Written by hand rather than generated, because the point of it is to be
/// *judged*: if the AI previews here do not read like something worth the tap,
/// the product idea has a problem that no amount of architecture fixes. Every
/// preview below obeys the same contract the real model is held to — say what
/// the thing is, say who might care, promise nothing.
///
/// Replaced wholesale by a backend: nothing outside `lib/data/mock` imports it.
