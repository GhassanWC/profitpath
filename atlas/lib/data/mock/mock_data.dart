  ///
  /// Mock video posts share three short clips so the real `video_player` path —
  /// buffering, progress, seeking, completion — is exercised rather than mimed.
  /// Each clip is a slow flight over the same map the app draws, rendered from
  /// the same Natural Earth outlines by `tool/make_sample_clips.py`; shipping
  /// stock footage the project has no licence to would have been the other
